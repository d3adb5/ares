/**
 * @file tests/unit/test_client_hdr.cpp
 * @brief Test src/client_hdr.h: the HDR display a client reports at launch.
 */
#include "../tests_common.h"

#include <src/client_hdr.h>

TEST(ClientHdr, ReadsTheLuminanceFields) {
  const auto display = client_hdr::parse("35400x14600x8500x39850x6550x2300x15635x16450x420x3230x210");
  ASSERT_TRUE(display);
  EXPECT_EQ(display->max_luminance, 420);
  EXPECT_EQ(display->min_luminance, 3230);
  EXPECT_EQ(display->max_frame_average, 210);
  EXPECT_TRUE(display->known());
}

TEST(ClientHdr, MoonlightsZerosSayNothing) {
  const auto display = client_hdr::parse("0x0x0x0x0x0x0x0x0x0x0");
  ASSERT_TRUE(display);
  EXPECT_FALSE(display->known());
}

TEST(ClientHdr, RefusesMalformedData) {
  for (const auto *text : {"", "0x0x0", "0x0x0x0x0x0x0x0x0x0x0x0", "0x0x0x0x0x0x0x0x420xx0", "0x0x0x0x0x0x0x0x70000x0x0", "0x0x0x0x0x0x0x0x4a0x0x0"}) {
    EXPECT_FALSE(client_hdr::parse(text)) << text;
  }
}
